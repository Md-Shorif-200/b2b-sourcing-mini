
-- ============================================
-- B2B Sourcing API
-- Database Schema
-- ============================================

-- Drop existing tables

DROP TABLE IF EXISTS quotations;
DROP TABLE IF EXISTS rfqs;
DROP TABLE IF EXISTS suppliers;
DROP TABLE IF EXISTS buyers;


-- ============================================
-- Buyers
-- ============================================

CREATE TABLE buyers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    company_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- ============================================
-- Suppliers
-- ============================================

CREATE TABLE suppliers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    company_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- ============================================
-- RFQs
-- ============================================

CREATE TABLE rfqs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id INTEGER NOT NULL,
    product_name TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN ('pending', 'approved', 'closed', 'cancelled')
        ),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (buyer_id)
        REFERENCES buyers(id)
        ON DELETE RESTRICT
);


-- ============================================
-- Quotations
-- ============================================

CREATE TABLE quotations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfq_id INTEGER NOT NULL,
    supplier_id INTEGER NOT NULL,

    unit_price NUMERIC(10, 2) NOT NULL
        CHECK (unit_price > 0),

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            status IN ('pending', 'selected', 'rejected')
        ),

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (rfq_id, supplier_id),

    FOREIGN KEY (rfq_id)
        REFERENCES rfqs(id)
        ON DELETE RESTRICT,

    FOREIGN KEY (supplier_id)
        REFERENCES suppliers(id)
        ON DELETE RESTRICT
);


-- ============================================
-- Indexes
-- ============================================

CREATE INDEX idx_rfqs_buyer_id
ON rfqs (buyer_id);

CREATE INDEX idx_rfqs_status
ON rfqs (status);

CREATE INDEX idx_quotations_rfq_id
ON quotations (rfq_id);

CREATE INDEX idx_quotations_supplier_id
ON quotations (supplier_id);
